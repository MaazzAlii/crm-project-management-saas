import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'
import {
  signOriginToken,
  verifyOriginToken,
  assertDestructiveActionAllowed,
  getImpersonationOriginSecret,
} from '@/lib/auth/impersonation'
import { logAuditEvent } from '@/lib/audit/log'

describe('ADMIN-1 Impersonation Security & Session Model', () => {
  const originalEnv = { ...process.env }

  beforeEach(() => {
    vi.restoreAllMocks()
    process.env = { ...originalEnv }
  })

  afterEach(() => {
    process.env = { ...originalEnv }
  })

  describe('Guardrail 1: Origin Cookie Signing & Secret Isolation', () => {
    it('throws CONFIG_ERROR in production if IMPERSONATION_ORIGIN_SECRET is missing', () => {
      process.env.NODE_ENV = 'production'
      delete process.env.IMPERSONATION_ORIGIN_SECRET

      expect(() => getImpersonationOriginSecret()).toThrowError(/CONFIG_ERROR/)
    })

    it('falls back to JWT_SECRET with warning in development if IMPERSONATION_ORIGIN_SECRET is unset', () => {
      process.env.NODE_ENV = 'development'
      delete process.env.IMPERSONATION_ORIGIN_SECRET
      process.env.JWT_SECRET = 'dev_jwt_secret_test_value_123456789'

      const secret = getImpersonationOriginSecret()
      expect(secret).toBe('dev_jwt_secret_test_value_123456789')
    })

    it('signs and verifies origin token payload correctly with IMPERSONATION_ORIGIN_SECRET', () => {
      process.env.IMPERSONATION_ORIGIN_SECRET = 'custom_impersonation_secret_abcdef123456'

      const payload = {
        superAdminId: '00000000-0000-0000-0000-superadmin01',
        impersonatedUserId: '00000000-0000-0000-0000-tenantuser01',
        impersonatedOrgId: '00000000-0000-0000-0000-tenantorg001',
        impersonatedOrgName: 'Acme Tenant Corp',
        impersonatedUserName: 'Jane Tenant',
        impersonatedUserEmail: 'jane@acme.com',
        startedAt: Date.now(),
        expiresAt: Date.now() + 3600_000,
      }

      const token = signOriginToken(payload)
      expect(typeof token).toBe('string')
      expect(token.split('.')).toHaveLength(3)

      const verified = verifyOriginToken(token)
      expect(verified).not.toBeNull()
      expect(verified?.superAdminId).toBe(payload.superAdminId)
      expect(verified?.impersonatedOrgId).toBe(payload.impersonatedOrgId)
      expect(verified?.impersonatedOrgName).toBe(payload.impersonatedOrgName)
    })

    it('rejects an origin token signed with a different or leaked session secret', () => {
      process.env.IMPERSONATION_ORIGIN_SECRET = 'secret_A_origin_secret_99999999999'
      const payload = {
        superAdminId: 'super-admin-id',
        impersonatedUserId: 'user-id',
        impersonatedOrgId: 'org-id',
        impersonatedOrgName: 'Org',
        impersonatedUserName: 'User',
        impersonatedUserEmail: 'user@example.com',
        startedAt: Date.now(),
        expiresAt: Date.now() + 3600_000,
      }
      const token = signOriginToken(payload)

      // Rotate secret or attempt verification with different secret
      process.env.IMPERSONATION_ORIGIN_SECRET = 'secret_B_different_secret_88888888888'
      const verified = verifyOriginToken(token)
      expect(verified).toBeNull()
    })
  })

  describe('Session Swapping & Tenant Isolation', () => {
    it('ensures mutations during impersonation target tenant org, not super-admin org', () => {
      const superAdminOrgId = '00000000-0000-0000-0000-org_super_admin'
      const tenantOrgId = '00000000-0000-0000-0000-org_target_tenant'

      // Simulated session context generated by getCurrentSessionContext when impersonating
      const impersonatedSession = {
        user: {
          id: '00000000-0000-0000-0000-tenant_user_x',
          email: 'user_x@tenant.com',
          fullName: 'User X',
          role: 'admin',
        },
        organization: {
          id: tenantOrgId,
          name: 'Tenant Org B',
          slug: 'tenant-org-b',
          planTier: 'pro',
        },
        role: 'admin',
        isSuperAdmin: false, // Super admin flag stripped so tenant role rules apply
        impersonation: {
          isImpersonated: true,
          superAdminId: '00000000-0000-0000-0000-super_admin_id',
          impersonatedOrgId: tenantOrgId,
          impersonatedOrgName: 'Tenant Org B',
          expiresAt: Date.now() + 3600_000,
        },
      }

      // Assert tenant scoping: organization.id strictly resolves to Tenant Org B, NEVER superAdminOrgId
      expect(impersonatedSession.organization.id).toBe(tenantOrgId)
      expect(impersonatedSession.organization.id).not.toBe(superAdminOrgId)
      expect(impersonatedSession.isSuperAdmin).toBe(false)
      expect(impersonatedSession.impersonation.isImpersonated).toBe(true)
    })
  })

  describe('Guardrail 2: Destructive Action Typed Confirmation', () => {
    const activeSession = {
      user: { id: 'user-1' },
      organization: { id: 'org-1', name: 'Acme Global Services' },
      impersonation: {
        isImpersonated: true,
        superAdminId: 'admin-1',
      },
    }

    it('rejects destructive action with 400 TYPED_CONFIRMATION_REQUIRED when confirmation is missing', () => {
      expect(() => {
        assertDestructiveActionAllowed(activeSession, undefined)
      }).toThrowError(/TYPED_CONFIRMATION_REQUIRED/)

      try {
        assertDestructiveActionAllowed(activeSession, undefined)
      } catch (err: any) {
        expect(err.code).toBe('TYPED_CONFIRMATION_REQUIRED')
        expect(err.status).toBe(400)
      }
    })

    it('rejects destructive action with 400 TYPED_CONFIRMATION_REQUIRED when typed name does not match', () => {
      expect(() => {
        assertDestructiveActionAllowed(activeSession, 'Wrong Name Inc')
      }).toThrowError(/TYPED_CONFIRMATION_REQUIRED/)

      try {
        assertDestructiveActionAllowed(activeSession, 'Wrong Name Inc')
      } catch (err: any) {
        expect(err.code).toBe('TYPED_CONFIRMATION_REQUIRED')
        expect(err.status).toBe(400)
      }
    })

    it('allows destructive action when typed organization name matches exactly', () => {
      expect(() => {
        assertDestructiveActionAllowed(activeSession, 'Acme Global Services')
      }).not.toThrow()
    })

    it('allows destructive action without confirmation when user is NOT impersonating', () => {
      const nonImpersonatedSession = {
        user: { id: 'owner-1' },
        organization: { id: 'org-1', name: 'Acme Global Services' },
        impersonation: { isImpersonated: false },
      }

      expect(() => {
        assertDestructiveActionAllowed(nonImpersonatedSession, undefined)
      }).not.toThrow()
    })
  })

  describe('Guardrail 3: Audit Log Auto-Injection', () => {
    it('automatically injects impersonated_by and impersonated_as when session is impersonated', async () => {
      const mockSession = {
        user: { id: '00000000-0000-0000-0000-tenantuser01', email: 'user@tenant.com' },
        organization: { id: '00000000-0000-0000-0000-tenantorg001', name: 'Tenant Org' },
        impersonation: {
          isImpersonated: true,
          superAdminId: '00000000-0000-0000-0000-superadmin01',
          impersonatedOrgId: '00000000-0000-0000-0000-tenantorg001',
        },
      }

      const db = await import('@/lib/db')
      const dbQuerySpy = vi.spyOn(db, 'query').mockResolvedValue({ rows: [], rowCount: 1 } as any)

      // Call logAuditEvent with explicit impersonated session context
      await logAuditEvent(
        {
          actorId: '00000000-0000-0000-0000-tenantuser01',
          action: 'CLIENT_DELETED',
          targetType: 'client',
          targetId: '00000000-0000-0000-0000-targetclient01',
          details: { clientId: 'client-999' },
        },
        mockSession as any
      )

      // Verify DB write includes impersonation provenance in details JSON
      const dbCalls = dbQuerySpy.mock.calls
      expect(dbCalls.length).toBeGreaterThan(0)
      const detailsArg = dbCalls[0][1][12] // details parameter ($13)
      const parsedDetails = typeof detailsArg === 'string' ? JSON.parse(detailsArg) : detailsArg

      expect(parsedDetails.impersonated_by).toBe('00000000-0000-0000-0000-superadmin01')
      expect(parsedDetails.impersonated_as).toBe('00000000-0000-0000-0000-tenantuser01')
      expect(parsedDetails.impersonated_org_id).toBe('00000000-0000-0000-0000-tenantorg001')
    })
  })
})
